const Character = ({ char, position = [0, 0, 0], color = '#2f24c1', delay = 0 }) => {
  const groupRef = useRef();
  const upperChar = char.toUpperCase();
  const pixels = characters[upperChar];

  useEffect(() => {
    if (!pixels) {
      console.warn(`Character "${char}" not defined in characters object.`);
      return;
    }

    // Animate the entire character group
    gsap.from(groupRef.current.position, {
      z: 80,
      duration: 0.6,
      ease: 'bounce.out',
      delay: delay,
    });
    gsap.from(groupRef.current, {
      opacity: 0,
      duration: 0.6,
      ease: 'linear',
      delay: delay,
    });
  }, [char, delay]);

  if (!pixels) {
    return null;
  }

  return (
    <group ref={groupRef} position={position}>
      {pixels.map((pixel, index) => (
        <Poxel
          key={index}
          position={[pixel[0], -pixel[1], 0]}
          color={color}
        />
      ))}
    </group>
  );
};

export default Character;
